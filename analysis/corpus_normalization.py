def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rule_values():
    return {
        "excluded_path_fragments": EXCLUDED_PATH_FRAGMENTS,
        "included_phrases": INCLUDED_PHRASES,
        "excluded_phrases": EXCLUDED_PHRASES,
    }


def rule_digest(rules):
    payload = json.dumps(rules, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(payload).hexdigest()


def notebook_values(path):
    values = {}
    notebook = json.loads(path.read_text(encoding="utf-8"))
    for cell in notebook["cells"]:
        try:
            tree = ast.parse("".join(cell.get("source", ())))
        except SyntaxError:
            continue
        for node in tree.body:
            if not isinstance(node, ast.Assign) or len(node.targets) != 1:
                continue
            target = node.targets[0]
            if isinstance(target, ast.Name) and target.id in (*RULE_NAMES, "ddl_indicator_phrases"):
                values[target.id] = tuple(ast.literal_eval(node.value))
    return values


