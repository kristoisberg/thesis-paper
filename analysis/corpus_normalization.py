def source_location(relative_path):
    parts = Path(relative_path).parts
    if any(
        parts[index : index + 2] == ("target", "generated-sources")
        for index in range(len(parts) - 1)
    ):
        return "target/generated-sources"
    return "src" if "src" in parts else "other"


def source_row(name, project, path):
    relative_path = path.relative_to(project).as_posix()
    if not path.is_file() or any(part in relative_path for part in EXCLUDED_PATH_FRAGMENTS):
        return None
    raw = path.read_bytes()
    text = decode_java(raw)
    if not any(phrase in text for phrase in INCLUDED_PHRASES):
        return None
    if any(phrase in text for phrase in EXCLUDED_PHRASES):
        return None
    return {
        "repository": name,
        "relative_path": relative_path,
        "source_location": source_location(relative_path),
        "source_role": (
            "generated schema"
            if any(phrase in text for phrase in DDL_INDICATOR_PHRASES)
            else "application/query source"
        ),
        "bytes": len(raw),
        "nonblank_loc": sum(bool(line.strip()) for line in text.splitlines()),
        "sha256": hashlib.sha256(raw).hexdigest(),
    }


def select_detector_sources(repositories, names):
    manifest = {}
    for name in names:
        project = repositories / name.replace("/", "_")
        for filename in glob.glob(str(project / "**/*.java"), recursive=True):
            row = source_row(name, project, Path(filename))
            if row is not None:
                manifest[(name, row["relative_path"])] = row
    return sorted(manifest.values(), key=lambda row: (row["repository"], row["relative_path"]))


def read_manifest(path, repositories):
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        assert tuple(reader.fieldnames or ()) == MANIFEST_FIELDS
        rows = list(reader)
    manifest = {(row["repository"], row["relative_path"]): row for row in rows}
    assert len(manifest) == EXPECTED_UNIQUE_FILES
    refreshed = []
    for repository, relative_path in manifest:
        project = repositories / repository.replace("/", "_")
        row = source_row(repository, project, project / relative_path)
        assert row is not None, f"manifest file no longer passes detector filters: {project / relative_path}"
        refreshed.append(row)
    return sorted(refreshed, key=lambda row: (row["repository"], row["relative_path"]))


def decode_java(raw):
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return raw.decode("cp1252", errors="replace")


def normalize_whitespace(text):
    return " ".join(text.split())


def fragment_alignment(fragment, span):
    if fragment.strip() == span.strip():
        return "trimmed_exact"
    fragment = normalize_whitespace(fragment)
    span = normalize_whitespace(span)
    if fragment == span:
        return "whitespace_normalized_exact"
    if fragment and fragment in span:
        return "archived_fragment_within_span"
    if span and span in fragment:
        return "source_span_within_archived_fragment"
    return "mismatch"


def source_frame_status(path, relative_path, contents, source):
    if source is not None:
        return source["source_location"]
    reasons = []
    if "src" not in Path(relative_path).parts:
        reasons.append("outside_src_tree")
    if any(part in str(path) for part in EXCLUDED_PATH_FRAGMENTS):
        reasons.append("excluded_path_fragment")
    if not any(phrase in contents for phrase in INCLUDED_PHRASES):
        reasons.append("missing_included_phrase")
    if any(phrase in contents for phrase in EXCLUDED_PHRASES):
        reasons.append("contains_excluded_phrase")
    return "+".join(reasons) or "unexplained"


def align_flags(path, repositories, name_to_project, manifest):
    by_source = {(row["repository"], row["relative_path"]): row for row in manifest}
    text_cache = {}
    alignments = []
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        frozen_fields = tuple(reader.fieldnames or ())
        flags = list(reader)
    assert len(flags) == EXPECTED_FLAGS, f"expected 15,931 flags, found {len(flags)}"

    for flag_row, row in enumerate(flags, 1):
        name = row["project_name"]
        project_name = row["Project"]
        relative_path = Path(row["File"]).as_posix()
        expected_project = name_to_project.get(name)
        source = by_source.get((name, relative_path))
        in_manifest = source is not None and expected_project == project_name
        exists = False
        span_ok = False
        alignment = "not_checked"
        fragment_in_file = False
        frame_status = "not_checked"
        source_role = ""
        source_hash = ""
        if expected_project == project_name:
            project = repositories / project_name
            candidate = project / relative_path
            try:
                source_path = candidate.resolve(strict=True)
            except FileNotFoundError:
                source_path = None
            if source_path is not None:
                assert source_path.is_relative_to(project.resolve()), f"path escapes repository: {source_path}"
                exists = source_path.is_file()
            if exists:
                if source_path not in text_cache:
                    raw = source_path.read_bytes()
                    decoded_text = decode_java(raw)
                    text_cache[source_path] = (
                        decoded_text.splitlines(),
                        normalize_whitespace(decoded_text),
                        hashlib.sha256(raw).hexdigest(),
                        (
                            "generated schema"
                            if any(phrase in decoded_text for phrase in DDL_INDICATOR_PHRASES)
                            else "application/query source"
                        ),
                        source_frame_status(source_path, relative_path, decoded_text, source),
                    )
                lines, normalized_source, source_hash, source_role, frame_status = text_cache[source_path]
                normalized_fragment = normalize_whitespace(row["Code fragment"])
                fragment_in_file = bool(normalized_fragment and normalized_fragment in normalized_source)
                line_from = int(row["Line from"])
                line_to = int(row["Line to"])
                span_ok = 1 <= line_from <= line_to <= len(lines)
                if span_ok:
                    alignment = fragment_alignment(
                        row["Code fragment"], "\n".join(lines[line_from - 1 : line_to])
                    )
        alignments.append(
            {
                "flag_row": flag_row,
                "repository": name,
                "project": project_name,
                "antipattern": row["Antipattern"],
                "relative_path": relative_path,
                "line_from": row["Line from"],
                "line_to": row["Line to"],
                "source_role": source_role,
                "source_sha256": source_hash,
                "source_file_exists": str(exists).lower(),
                "in_source_manifest": str(in_manifest).lower(),
                "source_frame_status": frame_status,
                "span_in_bounds": str(span_ok).lower(),
                "fragment_alignment": alignment,
                "fragment_found_in_source_file": str(fragment_in_file).lower(),
            }
        )
    return frozen_fields, flags, alignments


def reproduce_merged_results(project_results, names, name_to_project, frozen_fields, flags):
    expected_paths = {project_results / f"{name_to_project[name]}.csv" for name in names}
    actual_paths = set(project_results.glob("*.csv"))
    assert actual_paths == expected_paths, "per-project result files do not match the allowlist"
    reconstructed = []
    hashes = {}
    for name in names:
        path = project_results / f"{name_to_project[name]}.csv"
        hashes[path.name] = sha256(path)
        with path.open(newline="", encoding="utf-8") as handle:
            reader = csv.DictReader(handle)
            assert tuple(reader.fieldnames or ()) == PROJECT_RESULT_FIELDS, f"unexpected header: {path}"
            for row in reader:
                reconstructed.append((name, *(row[field] for field in PROJECT_RESULT_FIELDS)))
    frozen = [tuple(row[field] for field in frozen_fields) for row in flags]
    return Counter(reconstructed) == Counter(frozen), hashes


def format_rate(numerator, denominator, multiplier=1):
    return "" if not denominator else f"{multiplier * numerator / denominator:.6f}"


def quartiles(values):
    q1, _, q3 = statistics.quantiles(values, n=4, method="inclusive")
    return q1, statistics.median(values), q3


def size_stratum(file_count):
    if file_count <= SMALL_MAX_FILES:
        return "small"
    return "medium" if file_count <= MEDIUM_MAX_FILES else "large"


def density_summary(rows, scope):
    eligible_rows = [row for row in rows if row["eligible_files"]]
    densities = [100 * row["flags"] / row["eligible_files"] for row in eligible_rows]
    deciles = statistics.quantiles(densities, n=10, method="inclusive")
    q1, median, q3 = quartiles(densities)
    file_counts = [row["eligible_files"] for row in rows]
    flag_counts = [row["flags"] for row in rows]
    correlation = (
        statistics.correlation(file_counts, flag_counts, method="ranked")
        if len(set(file_counts)) > 1 and len(set(flag_counts)) > 1
        else None
    )
    return {
        "analysis_label": rows[0]["analysis_label"],
        "antipattern": rows[0]["antipattern"],
        "eligible_source_role": rows[0]["eligible_source_role"],
        "scope": scope,
        "repositories": len(rows),
        "repositories_with_eligible_files": len(eligible_rows),
        "flagged_repositories": sum(bool(row["flags"]) for row in rows),
        "total_flags": sum(flag_counts),
        "eligible_files": sum(file_counts),
        "pooled_flags_per_100_eligible_files": format_rate(
            sum(flag_counts), sum(file_counts), 100
        ),
        "repository_equal_mean_flags_per_100_eligible_files": f"{statistics.mean(densities):.6f}",
        "repository_p10_flags_per_100_eligible_files": f"{deciles[0]:.6f}",
        "repository_q1_flags_per_100_eligible_files": f"{q1:.6f}",
        "repository_median_flags_per_100_eligible_files": f"{median:.6f}",
        "repository_q3_flags_per_100_eligible_files": f"{q3:.6f}",
        "repository_p90_flags_per_100_eligible_files": f"{deciles[-1]:.6f}",
        "spearman_raw_flags_vs_eligible_files": (
            "" if correlation is None else f"{correlation:.6f}"
        ),
    }


def phase3_tables(repository_rows, manifest):
    corpus_files = Counter(row["repository"] for row in manifest)
    by_label = defaultdict(list)
    for row in repository_rows:
        by_label[row["analysis_label"]].append(row)

    density_rows = []
    concentration_rows = []
    selected_top_deciles = {}
    for label, rows in by_label.items():
        flagged_rows = [row for row in rows if row["flags"]]
        top_count = math.ceil(len(flagged_rows) * 0.10)
        ranked = sorted(flagged_rows, key=lambda row: (-row["flags"], row["repository"]))
        top_rows = ranked[:top_count]
        top_repositories = {row["repository"] for row in top_rows}
        selected_top_deciles[label] = top_repositories
        remaining_rows = [row for row in rows if row["repository"] not in top_repositories]
        cutoff = top_rows[-1]["flags"]
        tied = sum(row["flags"] == cutoff for row in flagged_rows)
        included_ties = sum(row["flags"] == cutoff for row in top_rows)
        above_cutoff = [row for row in flagged_rows if row["flags"] > cutoff]
        cutoff_rows = [row for row in flagged_rows if row["flags"] == cutoff]
        total_flags = sum(row["flags"] for row in rows)
        total_files = sum(row["eligible_files"] for row in rows)
        top_flags = sum(row["flags"] for row in top_rows)
        top_files = sum(row["eligible_files"] for row in top_rows)
        remaining_flags = sum(row["flags"] for row in remaining_rows)
        remaining_files = sum(row["eligible_files"] for row in remaining_rows)
        top_density = 100 * top_flags / top_files
        remaining_density = 100 * remaining_flags / remaining_files
        fixed_top_files = sum(row["eligible_files"] for row in above_cutoff)
        tied_file_counts = sorted(row["eligible_files"] for row in cutoff_rows)
        min_top_files = fixed_top_files + sum(tied_file_counts[:included_ties])
        max_top_files = fixed_top_files + sum(tied_file_counts[-included_ties:])
        min_density_ratio = (top_flags / max_top_files) / (
            remaining_flags / (total_files - max_top_files)
        )
        max_density_ratio = (top_flags / min_top_files) / (
            remaining_flags / (total_files - min_top_files)
        )

        concentration_rows.append(
            {
                "analysis_label": label,
                "antipattern": rows[0]["antipattern"],
                "eligible_source_role": rows[0]["eligible_source_role"],
                "flagged_repositories": len(flagged_rows),
                "top_decile_repositories": top_count,
                "cutoff_flags": cutoff,
                "repositories_tied_at_cutoff": tied,
                "cutoff_ties_included": included_ties,
                "total_flags": total_flags,
                "top_decile_flags": top_flags,
                "top_decile_flag_share_percent": format_rate(top_flags, total_flags, 100),
                "eligible_files": total_files,
                "top_decile_eligible_files": top_files,
                "top_decile_eligible_file_share_percent": format_rate(
                    top_files, total_files, 100
                ),
                "top_decile_eligible_file_share_min_percent": format_rate(
                    min_top_files, total_files, 100
                ),
                "top_decile_eligible_file_share_max_percent": format_rate(
                    max_top_files, total_files, 100
                ),
                "top_decile_flags_per_100_eligible_files": f"{top_density:.6f}",
                "remaining_flags": remaining_flags,
                "remaining_eligible_files": remaining_files,
                "remaining_flags_per_100_eligible_files": f"{remaining_density:.6f}",
                "top_to_remaining_density_ratio": f"{top_density / remaining_density:.6f}",
                "top_to_remaining_density_ratio_min": f"{min_density_ratio:.6f}",
                "top_to_remaining_density_ratio_max": f"{max_density_ratio:.6f}",
            }
        )
        scopes = [
            ("all repositories", rows),
            ("excluding highest-count decile", remaining_rows),
        ]
        scopes.extend(
            (
                f"{stratum} repositories",
                [
                    row
                    for row in rows
                    if size_stratum(corpus_files[row["repository"]]) == stratum
                ],
            )
            for stratum in ("small", "medium", "large")
        )
        density_rows.extend(density_summary(scope_rows, scope) for scope, scope_rows in scopes)
    return density_rows, concentration_rows, selected_top_deciles


